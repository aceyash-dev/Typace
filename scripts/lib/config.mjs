/**
 * Shared paths and constants for the generators in scripts/.
 *
 * Both generators used to hardcode process.cwd(), so running either from
 * anywhere but the repository root failed with a raw ENOENT or, worse, wrote to
 * the wrong tree. Resolving from this file's own location makes the scripts
 * location-independent, and the environment overrides let CI point them
 * elsewhere without editing code.
 */
import path from "node:path";
import { fileURLToPath } from "node:url";

export const FONT_EXTENSIONS = new Set([".ttf", ".otf", ".woff", ".woff2"]);

/** Repository root, derived from scripts/lib/config.mjs. */
export const REPO_ROOT = path.resolve(fileURLToPath(new URL("../..", import.meta.url)));

export const FONTS_DIR = process.env.FONTS_DIR
    ? path.resolve(process.env.FONTS_DIR)
    : path.join(REPO_ROOT, "fonts");

export const STYLE_INDEX_PATH = process.env.STYLE_INDEX_OUT
    ? path.resolve(process.env.STYLE_INDEX_OUT)
    : path.join(FONTS_DIR, "style-index.json");

export const MANIFEST_PATH = process.env.FONT_MANIFEST_OUT
    ? path.resolve(process.env.FONT_MANIFEST_OUT)
    : path.join(FONTS_DIR, "manifest.json");

export const STYLE_INDEX_NOTE = "Generated by scripts/font-style-index.mjs from sfnt tables. Do not edit by hand. Files listed in 'unsupported' are compressed containers whose tables cannot be read without a WOFF2 decoder, so they carry no style data.";

export const MANIFEST_NOTE = "Generated by scripts/font-manifest.mjs from git history. Do not edit by hand.";

/** Font files under `directory`, sorted the way every artifact is keyed. */
export function listFontFilesSync(readdir, directory) {
    return readdir(directory)
        .filter((name) => FONT_EXTENSIONS.has(path.extname(name).toLowerCase()))
        .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));
}
